// Data access tests
// ============================================================================
static void test_data_access() {
    run_test("get_byte_at_offset", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto val = pe.get_byte_at_offset(0);
        ASSERT_EQ(val, 0x4D);
    });
    run_test("get_word_at_offset", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto val = pe.get_word_at_offset(0);
        ASSERT_EQ(val, 0x5A4D);
    });
    run_test("get_dword_at_offset", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto val = pe.get_dword_at_offset(0x40);
        ASSERT_EQ(val, 0x00004550);
    });
    run_test("get_byte_at_offset out of bounds returns 0", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto val = pe.get_byte_at_offset(0xFFFFFFFF);
        ASSERT_EQ(val, 0);
    });
    run_test("get_string_at_rva", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto str = pe.get_string_at_rva(0x40, 2);
        ASSERT_EQ(str, "PE");
    });
    run_test("get_memory_mapped_image", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto mapped = pe.get_memory_mapped_image();
        ASSERT_TRUE(mapped.size() > 0);
        ASSERT_EQ(mapped[0], 0x4D);
        ASSERT_EQ(mapped[1], 0x5A);
    });
}

