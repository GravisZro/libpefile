static void test_file_operations() {
    run_test("write to file and read back", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        std::string filename = "/tmp/test_pe_output.exe";
        ASSERT_TRUE(pe.write(filename));

        PE pe2(filename);
        ASSERT_EQ(pe2.dos_header().e_magic, 0x5A4D);
        ASSERT_EQ(pe2.file_header().Machine, 0x14C);

        std::remove(filename.c_str());
    });
    run_test("file not found throws exception", []() {
        ASSERT_THROW(PE("/nonexistent/path/to/file.exe"), std::runtime_error);
    });
}

