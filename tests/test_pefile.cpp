// ============================================================================
// Error handling tests
// ============================================================================
static void test_error_handling() {
    run_test("empty file throws PEFormatError", []() {
        std::vector<uint8_t> data(64, 0);
        ASSERT_THROW(PE(data), PEFormatError);
    });
    run_test("too small data throws PEFormatError", []() {
        std::vector<uint8_t> data(10, 0);
        ASSERT_THROW(PE(data), PEFormatError);
    });
    run_test("invalid DOS signature throws PEFormatError", []() {
        std::vector<uint8_t> data(64, 0);
        data[0] = 'N'; data[1] = 'O';
        ASSERT_THROW(PE(data), PEFormatError);
    });
    run_test("invalid NT signature throws PEFormatError", []() {
        auto data = make_minimal_pe32();
        data[0x40] = 'X'; data[0x41] = 'X'; data[0x42] = 'X'; data[0x43] = 'X';
        ASSERT_THROW(PE(data), PEFormatError);
    });
    run_test("valid DOS header but truncated throws PEFormatError", []() {
        std::vector<uint8_t> data(0x40, 0);
        data[0] = 0x4D; data[1] = 0x5A;
        uint32_t lfanev = 0x40;
        std::memcpy(data.data() + 0x3C, &lfanev, 4);
        ASSERT_THROW(PE(data), PEFormatError);
    });
}

// ============================================================================
// Basic PE parsing tests
// ============================================================================
static void test_basic_parsing() {
    run_test("parse minimal PE32", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        ASSERT_EQ(pe.dos_header().e_magic, 0x5A4D);
        ASSERT_EQ(pe.file_header().Machine, 0x14C);
        ASSERT_EQ(pe.file_header().NumberOfSections, 1);
        ASSERT_TRUE(pe.is_exe());
        ASSERT_FALSE(pe.is_dll());
        ASSERT_FALSE(pe.is_driver());
        ASSERT_TRUE(pe.sections().size() == 1);
        ASSERT_EQ(pe.sections()[0].name(), ".text");
    });
    run_test("parse minimal PE32 DLL", []() {
        auto data = make_minimal_pe32_dll();
        PE pe(data);
        ASSERT_FALSE(pe.is_exe());
        ASSERT_TRUE(pe.is_dll());
    });
    run_test("parse minimal PE64", []() {
        auto data = make_minimal_pe64();
        PE pe(data);
        ASSERT_TRUE(pe.is_pe32_plus());
        ASSERT_EQ(pe.file_header().Machine, 0x8664);
        ASSERT_TRUE(pe.is_exe());
        ASSERT_FALSE(pe.is_dll());
    });
    run_test("fast_load skips data directories", []() {
        auto data = make_minimal_pe32();
        PE pe(data, true);
        ASSERT_EQ(pe.dos_header().e_magic, 0x5A4D);
        ASSERT_TRUE(pe.imports().empty());
    });
    run_test("get_section_by_rva", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto sec = pe.get_section_by_rva(0x1000);
        ASSERT_TRUE(sec.has_value());
        auto sec2 = pe.get_section_by_rva(0x5000);
        ASSERT_FALSE(sec2.has_value());
    });
    run_test("get_offset_from_rva", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto offset = pe.get_offset_from_rva(0x1000);
        ASSERT_EQ(offset, 0x200);
    });
    run_test("get_rva_from_offset", []() {
        auto data = make_minimal_pe32();
        PE pe(data);
        auto rva = pe.get_rva_from_offset(0x200);
        ASSERT_EQ(rva, 0x1000);
    });
}

