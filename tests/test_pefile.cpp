// Driver detection tests
// ============================================================================
static void test_driver_detection() {
    run_test("PE with subsystem NATIVE is driver", []() {
        test_helpers::PeBuilder b(false);
        b.set_machine(0x14C);
        b.set_characteristics(0x0102);
        b.set_subsystem(1);
        b.set_entry_point(0x1000);
        b.set_num_sections(1);
        b.add_section(".text", 0x100, 0x1000, 0x200, 0x200, 0x60000020);
        auto d = b.build();
        PE pe(d);
        ASSERT_TRUE(pe.is_driver());
    });
    run_test("PE with subsystem EFI_APPLICATION is driver", []() {
        test_helpers::PeBuilder b(false);
        b.set_machine(0x14C);
        b.set_characteristics(0x0102);
        b.set_subsystem(10);
        b.set_entry_point(0x1000);
        b.set_num_sections(1);
        b.add_section(".text", 0x100, 0x1000, 0x200, 0x200, 0x60000020);
        auto d = b.build();
        PE pe(d);
        ASSERT_TRUE(pe.is_driver());
    });
    run_test("PE with subsystem GUI is not driver", []() {
        test_helpers::PeBuilder b(false);
        b.set_machine(0x14C);
        b.set_characteristics(0x0102);
        b.set_subsystem(2);
        b.set_entry_point(0x1000);
        b.set_num_sections(1);
        b.add_section(".text", 0x100, 0x1000, 0x200, 0x200, 0x60000020);
        auto d = b.build();
        PE pe(d);
        ASSERT_FALSE(pe.is_driver());
    });
}

