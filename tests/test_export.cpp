static void run_test(const char* name, std::function<void()> fn)
{
  tests_run++;
  try
  {
    fn();
    tests_passed++;
    std::cout << "  PASS: " << name << "\n";
  }
  catch (const std::exception& e)
  {
    tests_failed++;
    std::cout << "  FAIL: " << name << "\n  " << e.what() << "\n";
  }
}

